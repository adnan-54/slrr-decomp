#!/usr/bin/env python3
"""rtti.json -> analysis/names.json (address->name list for Ghidra) + notes/classes.md"""
import json, sys, re, collections
j = json.load(open(sys.argv[1]))
cls = j['classes']
def ident(n):  # symbol-safe
    return re.sub(r'[^A-Za-z0-9_]+', '_', n).strip('_')
use = collections.Counter()
for n, vs in cls.items():
    for v in vs:
        for f in set(v['vfuncs']): use[f] += 1
names = {}
for n, vs in sorted(cls.items()):
    for k, v in enumerate(vs):
        suf = '' if len(vs) == 1 else f'_{k}'
        names[v['vftable']] = f'vftable_{ident(n)}{suf}'
        for i, f in enumerate(v['vfuncs']):
            if use[f] == 1 and f not in names:
                names[f] = f'{ident(n)}__vf{i}'
seen = collections.Counter(names.values())
for a, nm in list(names.items()):
    if seen[nm] > 1: names[a] = f'{nm}_{a[2:]}'   # keep names unique (several classes share an ident)
json.dump(names, open(sys.argv[2], 'w'), indent=0, sort_keys=True)
shared = sum(1 for f, c in use.items() if c > 1)
print('names', len(names), 'vftables', sum(len(v) for v in cls.values()), 'unique vfuncs', sum(1 for c in use.values() if c == 1), 'shared vfuncs', shared)
with open(sys.argv[3], 'w') as o:
    o.write('# C++ classes recovered from MSVC RTTI\n\nGenerated by `tools/rtti.py` + `tools/rtti_names.py` from the exe (sha256 f44fb88a…). '
            'Image base 0x400000. `bases` = RTTI base-class list (first = direct parent). `vf` = number of virtual slots seen '
            '(vftable end is detected by the next COL pointer or a non-.text entry, so can be short).\n\n'
            '| class | vftable | vf | bases |\n|---|---|---|---|\n')
    for n, vs in sorted(cls.items()):
        for v in vs:
            o.write(f"| `{n}` | {v['vftable']} | {v['nvfuncs']} | {', '.join(v['bases'][:4])}{'…' if len(v['bases'])>4 else ''} |\n")
